export function keywordValueScore(name: string): number {
  const n = name.toLowerCase();
  let best = 0;
  for (const [kw, score] of Object.entries(KEYWORD_MAP)) {
    if (n.includes(kw)) {
      // Full score if keyword is at start or end (more brandable position)
      const positional =
        n.startsWith(kw) || n.endsWith(kw)
          ? score
          : Math.round(score * 0.65);
      best = Math.max(best, positional);
    }
  }
  return best;
}
